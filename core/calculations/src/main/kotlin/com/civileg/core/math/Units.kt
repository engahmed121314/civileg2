package com.civileg.core.math

/**
 * وحدة الطول مع عوامل التحويل إلى الوحدة الأساسية (المليمتر).
 *
 * الوحدة الأساسية: مم (متوافقة مع اتفاقية الكود: widthMm, depthMm, coverMg).
 * المرجع: KSI / SI Brochure (BIPM); ASTM E380 / IEEE-ASTM SI 10 للتحويل للبريطاني-الأمريكي.
 *
 * عوامل التحويل معرفة كثوابت سمية — لا توجد قيم حرفيّة مكشوفة (no hardcoded constants).
 */
enum class LengthUnit(val toBaseMm: Double) {
    /** مليمتر — الوحدة الأساسية */
    MM(1.0),
    /** سم = 10 مم */
    CM(10.0),
    /** متر = 1000 مم */
    M(1000.0),
    /** كم = 1,000,000 مم */
    KM(1_000_000.0),

    /** بوصة = 25.4 مم بالضبط (بالتعريف، ASTM E380) */
    IN(25.4),
    /** قدم = 12 بوصة = 304.8 مم */
    FT(304.8),
    /** ياردة = 3 أقدام = 914.4 مم */
    YD(914.4),
    /** ميل = 1760 ياردة = 1,609,344 مم */
    MILE(1_609_344.0);

    /**
     * يحول قيمة من هذه الوحدة إلى الأمتار (م).
     */
    fun toM(value: Double): Double = value * toBaseMm / 1000.0

    /**
     * يحول قيمة من الأمتار (م) إلى هذه الوحدة.
     */
    fun fromM(value: Double): Double = value * 1000.0 / toBaseMm
}

/**
 * وحدة القوة مع عوامل التحويل إلى الوحدة الأساسية (نيوتن).
 *
 * الوحدة الأساسية: نيوتن (N).
 * المرجع: SI Brochure (BIPM); 1 lbf = 4.4482216152605 N (بالتعريف، الجاذبية القياسية).
 */
enum class ForceUnit(val toBaseN: Double) {
    /** نيوتن — الوحدة الأساسية */
    N(1.0),
    /** كيلو نيوتن = 1000 N */
    kN(1000.0),
    /** ميغا نيوتن = 1,000,000 N */
    MN(1_000_000.0),
    /** جيجا نيوتن = 1,000,000,000 N */
    GN(1_000_000_000.0),

    /** رطل-قوة = 4.4482216152605 N (بالتعريف) */
    lbf(4.4482216152605),
    /**キب = 1000 lbf */
    kip(4448.2216152605),
    /** كيلوغرام-قوة = 9.80665 N (الجاذبية القياسية) */
    kgf(9.80665),
    /** طن-قوة مترى = 1000 kgf = 9806.65 N */
    tf(9806.65);
}

/**
 * وحدة الإجهاد مع عوامل التحويل إلى الوحدة الأساسية (ميغا باسكال = N/مم²).
 *
 * الوحدة الأساسية: MPa (= N/mm²) — متوافق مع الكود (fcuMpa, fyMpa).
 * المرجع: SI Brochure (BIPM); 1 ksi = 6.894757293168 MPa.
 */
enum class StressUnit(val toBaseMpa: Double) {
    /** باسكال = 10^-6 MPa */
    Pa(0.000001),
    /** كيلو باسكال = 10^-3 MPa */
    kPa(0.001),
    /** ميغا باسكال = 1 N/مم² — الوحدة الأساسية */
    MPa(1.0),
    /** جيجا باسكال = 1000 MPa */
    GPa(1000.0),

    /** رطل/بوصة² = 0.006894757293168 MPa */
    psi(0.006894757293168),
    /** كيلو رطل/بوصة² = 6.894757293168 MPa */
    ksi(6.894757293168),
    /** رطل/قدم² = psi / 144 */
    psf(0.0000478802589888),
    /** كيلوغرام-قوة/سم² = 0.0980665 MPa */
    kgfCm2(0.0980665);
}

/**
 * وحدة العزوم مع عوامل التحويل إلى الوحدة الأساسية (نيوتن·مليمتر).
 *
 * الوحدة الأساسية: N·mm — متوافق مع الطول (مم) والقوة (نيوتن):
 *   عزوم = قوة × طول = N × mm = N·mm ✓ (بعدي متطابق)
 * المرجع: SI Brochure (BIPM).
 */
enum class MomentUnit(val toBaseNmm: Double) {
    /** نيوتن·مم — الوحدة الأساسية */
    Nmm(1.0),
    /** نيوتن·متر = 1000 N·mm */
    Nm(1000.0),
    /** كيلو نيوتن·مم = 1000 N·mm */
    kNmm(1000.0),
    /** كيلو نيوتن·متر = 1,000,000 N·mm */
    kNm(1_000_000.0),

    /** رطل-قوة·بوصة = 112.9848290276 N·mm */
    lbfIn(112.9848290276),
    /** رطل-قوة·قدم = 1355.8179483314 N·mm */
    lbfFt(1355.8179483314),
    /**キب·بوصة = 112984.8290276 N·mm */
    kipIn(112984.8290276),
    /**키ب·قدم = 1355817.9483314 N·mm */
    kipFt(1355817.9483314);
}
