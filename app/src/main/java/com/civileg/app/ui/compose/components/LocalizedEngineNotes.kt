/**
 * Display text for a note or warning generated by a calculation engine.
 *
 * The engines write English notes. A note that matches a known pattern is shown from
 * the string resources (ar and en), with the numbers carried over; any other note is
 * shown unchanged, so nothing is hidden when a new note is added.
 */
@Composable
fun localizedEngineNote(note: String): String {
    for (rule in noteRules) {
        val m = rule.regex.find(note) ?: continue
        val args = m.groupValues.drop(1).toTypedArray()
        return if (args.isEmpty()) stringResource(rule.resId) else stringResource(rule.resId, *args)
    }
    return note
}
